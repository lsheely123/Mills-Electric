#!/bin/sh
# Assembles the publishable site into deploy/ for Cloudflare Pages.
# Everything not listed here (brand_assets, tools, _archive, growth, screenshots)
# stays private.
#
#   ./make-deploy.sh            build deploy/ only
#   ./make-deploy.sh --deploy   build, then upload to the mills-electric Pages project
#                               (staging: https://mills-electric.pages.dev)
#
# Deploys are a direct upload, never a Git hook (Isidore SITES.md rule 2), so pushing
# to GitHub never changes the live site by itself.
set -e
cd "$(dirname "$0")"

case "${1:-}" in
  ""|--deploy) ;;
  *) echo "usage: ./make-deploy.sh [--deploy]" >&2; exit 2 ;;
esac

# --- regenerate the town pages from their generator ---------------------------
# tools/make-town-pages.py owns their HTML, so a stale page can never ship.
python3 tools/make-town-pages.py >/dev/null

# --- clean the build dir without rm -rf ---------------------------------------
if [ -e deploy ] && [ ! -d deploy ]; then
  echo "refusing to build: ./deploy exists and is not a directory" >&2
  exit 1
fi
mkdir -p deploy
find deploy -mindepth 1 -delete

# --- guard: designer source art must never reach assets/ ----------------------
# cp -R assets deploy/ publishes everything under assets/, so a source board
# dropped there would go live. Source art belongs in brand_assets/logos/_source/.
if find assets \( -iname 'board-*' -o -iname 'transparent-*' -o -name '_source' \) \
     -print 2>/dev/null | grep -q .; then
  echo "refusing to build: designer source art found under assets/ —" >&2
  find assets \( -iname 'board-*' -o -iname 'transparent-*' -o -name '_source' \) >&2
  echo "move it to brand_assets/logos/_source/ and rebuild" >&2
  exit 1
fi

# --- core pages ---------------------------------------------------------------
cp index.html services.html about.html contact.html reviews.html 404.html deploy/

# --- town service-area pages (generated by tools/make-town-pages.py) ----------
# Glob, not a list, so adding a town page needs no edit here.
for f in electrician-*-ma.html; do
  [ -e "$f" ] || { echo "refusing to build: no town pages found" >&2; exit 1; }
  cp "$f" deploy/
done

# --- crawler files ------------------------------------------------------------
# Both contain the literal https://REPLACE-DOMAIN until the domain is set.
cp sitemap.xml robots.txt deploy/

# --- Cloudflare Pages headers (noindex on the staging address) ----------------
cp _headers deploy/

cp -R assets deploy/

# macOS sprinkles .DS_Store through any folder it has been browsed in, and
# cp -R faithfully publishes them. Strip them from the build.
find deploy -name '.DS_Store' -delete

# --- post-build sanity --------------------------------------------------------
pages=$(find deploy -maxdepth 1 -name '*.html' | wc -l | tr -d ' ')
if [ "$pages" -ne 14 ]; then
  echo "WARNING: expected 14 html pages in deploy/, found $pages" >&2
fi

echo "deploy/ ready — $(find deploy -type f | wc -l | tr -d ' ') files, $(du -sh deploy | cut -f1), ${pages} pages"
find deploy -type f | sed 's|^deploy/|  |' | sort

# --- optional upload to Cloudflare Pages ---------------------------------------
if [ "${1:-}" = "--deploy" ]; then
  if ! command -v npx >/dev/null 2>&1; then
    # Node lives under nvm on this Mac and isn't on the default PATH.
    for d in "$HOME"/.nvm/versions/node/*/bin; do [ -x "$d/npx" ] && PATH="$d:$PATH"; done
  fi
  command -v npx >/dev/null 2>&1 || { echo "deploy: npx not found; install Node first" >&2; exit 1; }
  CLOUDFLARE_ACCOUNT_ID=1bc1f76c5970d9147a37c9952abf6141 \
    npx --yes wrangler pages deploy deploy --project-name mills-electric --branch main
fi
